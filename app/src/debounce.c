void init_button(button_t *p_sbtn, uint32_t p_gpio_periph, uint32_t p_pin) {
    p_sbtn->gpio_periph = p_gpio_periph;
    p_sbtn->pin = p_pin;
    p_sbtn->state = 0x0000; // Initial state for debounce
}

bool debounce(button_t *p_sbtn) {
  p_sbtn->state = (p_sbtn->state<<1) | gpio_input_bit_get(p_sbtn->gpio_periph, p_sbtn->pin) | 0xffe0;
  return (p_sbtn->state == 0xfff0);
}
